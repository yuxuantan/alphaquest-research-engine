class ResultBundleV2(BaseModel):
    """Sole strict-JSON source for Studio result presentation."""

    model_config = ConfigDict(extra="forbid", populate_by_name=True, strict=True)

    schema_name: Literal["alphaquest.result-bundle/v2"] = Field(
        default=RESULT_BUNDLE_SCHEMA,
        alias="schema",
        serialization_alias="schema",
    )
    campaign_id: str
    variant_id: str
    run_id: str
    generated_at: datetime
    verdict: Literal["PASS", "FAIL", "NEEDS MANUAL REVIEW"]
    verdict_message: str
    scientific_validity_verdict: Literal["PASS", "FAIL", "NEEDS MANUAL REVIEW"] = (
        "NEEDS MANUAL REVIEW"
    )
    generic_objective_verdict: Literal["PASS", "FAIL", "NEEDS MANUAL REVIEW"] | None = None
    metrics: ScalarMetricsV2
    stage_criteria: list[StageCriterionV2] = Field(default_factory=list)
    breakdowns: BreakdownArtifactsV2
    supplemental_artifacts: SupplementalArtifactsV2
    analysis_artifacts: AnalysisArtifactsV2 = Field(default_factory=_legacy_analysis_artifacts)

    @field_validator("campaign_id", "variant_id", "run_id", "verdict_message")
    @classmethod
    def _required_text(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("value must be non-empty")
        return value.strip()

    @field_validator("generated_at")
    @classmethod
    def _timezone_aware(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("generated_at must be timezone-aware")
        return value

    @model_validator(mode="after")
    def _candidate_only_pass_language(self) -> "ResultBundleV2":
        if self.generic_objective_verdict is None:
            self.generic_objective_verdict = self.verdict
        elif self.generic_objective_verdict != self.verdict:
            raise ValueError("generic_objective_verdict must match the ResultBundleV2 verdict")
        if self.verdict == "PASS" and "candidate strategy only" not in self.verdict_message.casefold():
            raise ValueError("PASS language must say 'candidate strategy only'")
        if self.scientific_validity_verdict == "PASS":
            validity = [
                item
                for item in self.stage_criteria
                if item.decision_role == "scientific_validity"
            ]
            if not validity or any(item.result != "PASS" for item in validity):
                raise ValueError(
                    "scientific-validity PASS requires explicit passing validity criteria"
                )
            if any(item.decision_role is None for item in self.stage_criteria):
                raise ValueError(
                    "scientific-validity PASS requires every criterion to declare decision_role"
                )
        return self


