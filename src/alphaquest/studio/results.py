def _numeric_column(trades: pd.DataFrame, *names: str) -> pd.Series:
    name = next((candidate for candidate in names if candidate in trades.columns), None)
    if name is None:
        return pd.Series(dtype=float)
    return pd.to_numeric(trades[name], errors="coerce").dropna().astype(float)


def _max_streak(pnl: pd.Series, *, winning: bool) -> int:
    current = maximum = 0
    for value in pnl:
        matches = value > 0 if winning else value < 0
        current = current + 1 if matches else 0
        maximum = max(maximum, current)
    return int(maximum)


def _safe_ratio(numerator: float | int | None, denominator: float | int | None) -> float | None:
    if numerator is None or denominator is None or float(denominator) == 0:
        return None
    value = float(numerator) / float(denominator)
    return value if math.isfinite(value) else None


def _finite_native(value: float | int | None) -> float | int | None:
    if value is None:
        return None
    if isinstance(value, int):
        return value
    numeric = float(value)
    return numeric if math.isfinite(numeric) else None


