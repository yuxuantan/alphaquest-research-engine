def _monte_carlo_bands(frame: pd.DataFrame | None) -> pd.DataFrame:
    if frame is None or frame.empty:
        return pd.DataFrame(columns=["sequence", "p05", "p50", "p95"])
    quantiles = [
        name
        for name in frame.columns
        if re.match(r"^(p0?5|p50|p95|q0?[._]?05|q0?[._]?5|q0?[._]?95)$", str(name), flags=re.IGNORECASE)
    ]
    if len(quantiles) < 2:
        return pd.DataFrame(columns=["sequence", "p05", "p50", "p95"])
    sequence = next((name for name in ("sequence", "trade_sequence", "step") if name in frame.columns), None)
    selected = [sequence, *quantiles] if sequence else quantiles
    result = frame.loc[:, [name for name in selected if name]].copy()
    if sequence is None:
        result.insert(0, "sequence", range(1, len(result) + 1))
    return result


